#!/usr/bin/env python3
"""Create (or top up) the repo's phase folders from docs/data/roadmap.json.

Safe to re-run. It regenerates the README.md files (roadmap content) but never
overwrites your own files: notes.md, logs, attempts, experiments, figures.

    python scripts/build_roadmap.py   # after editing the plan
    python scripts/scaffold.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = json.loads((ROOT / "docs/data/roadmap.json").read_text(encoding="utf-8"))
SITE = "https://arubad.github.io/AI_Research_Journey/"
GEN = "<!-- Generated by scripts/scaffold.py from docs/data/roadmap.json. Edit the data, not this file. -->\n"
P = {p["id"]: p for p in D["phases"]}
made: list[str] = []


def slug(s: str, n: int = 48) -> str:
    s = re.sub(r"\$[^$]*\$|`[^`]*`|\[[^\]]*\]\([^)]*\)", " ", s)
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:n].strip("-") or "item"


def readme(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GEN + text.rstrip() + "\n", encoding="utf-8")


def keep(path: Path, text: str) -> None:
    """Write only if missing — these are the owner's files."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(text.rstrip() + "\n", encoding="utf-8")
        made.append(str(path.relative_to(ROOT)))


def gitkeep(d: Path) -> None:
    d.mkdir(parents=True, exist_ok=True)
    if not any(p for p in d.iterdir() if p.name != ".gitkeep"):
        (d / ".gitkeep").touch()


def paras(xs) -> str:
    return "\n\n".join(xs or [])


def head(ph) -> str:
    return f"# Phase {ph['num']}: {ph['title']}\n\n*{ph['weeks']}* · [Track on the site]({SITE}#{ph['id']})\n\n{paras(ph['intro'])}\n"


def sources(s: str) -> str:
    return f"\n\nSources: {s}\n" if s else ""


def mdrow(cells) -> str:
    return "| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in cells) + " |"


def table(headers, rows) -> str:
    return "\n".join([mdrow(headers), mdrow(["---"] * len(headers))] + [mdrow(r) for r in rows])


# ---------------------------------------------------------------- phase 0
def phase0():
    ph, d = P["p0"], ROOT / "phase-0-cs336"
    lect = table(["Lecture", "Topic", "Why it shows up in interviews", "Paper(s) it unlocks", "Assignment"],
                 [[" · ".join(f"[{l['label']}]({l['url']})" for l in x["links"]), x["topic"], x["why"], x["papers"], x["assignment"]] for x in ph["lectures"]])
    assigns = "\n".join(f"- [{a['label']}]({a['url']}) — {a['tag']}" for a in ph["assignments"])
    readme(d / "README.md", f"""{head(ph)}
[YouTube playlist](https://www.youtube.com/playlist?list={ph['playlist']['list']})

{lect}

## Assignments
{assigns}

{paras(ph['after'])}

## In this folder
| Path | What goes there |
| --- | --- |
| `notes/` | One file per lecture: notes plus the one diagram you drew |
| `assignments/` | Your clones of the official assignment repos (check the course's policy before publishing solutions) |
{sources(ph['sources'])}""")
    for x in ph["lectures"]:
        n = x["n"].replace("–", "-")
        keep(d / "notes" / f"L{'-'.join(k.zfill(2) for k in n.split('-'))}-{slug(x['topic'])}.md",
             f"# CS336 Lecture {x['n']}: {x['topic']}\n\nLinks: " + ", ".join(f"[{l['label']}]({l['url']})" for l in x["links"]) +
             f"\n\nWhy it matters: {x['why']}\nUnlocks: {x['papers']}\n\n## Notes\n\n## Diagram\n\n## Questions\n")
    gitkeep(d / "assignments")


# ---------------------------------------------------------------- phase 1
def phase1():
    ph, d = P["p1"], ROOT / "phase-1-math"
    rows = table(["#", "Area", "Derive by hand", "Confirm in code (HAND, under 20 lines)", "Used in paper", "File"],
                 [[r["id"], r["area"], r["derive"], r["code"], r["paper"], f"`derivations/{r['id']}-{slug(r['derive'], 36)}.md`"] for r in ph["rows"]])
    readme(d / "README.md", f"""{head(ph)}
{rows}

{paras(ph['after'])}

## In this folder
| Path | What goes there |
| --- | --- |
| `derivations/` | One file per row: the pen-and-paper derivation (photo or LaTeX) |
| `checks/` | The under-20-line scripts that confirm each derivation numerically |
{sources(ph['sources'])}""")
    for r in ph["rows"]:
        keep(d / "derivations" / f"{r['id']}-{slug(r['derive'], 36)}.md",
             f"# {r['id']} · {r['area']}\n\n**Derive by hand:** {r['derive']}\n\n**Confirm in code:** {r['code']}\n\n**Used in:** {r['paper']}\n\n## Derivation\n\n## Numerical check\n\nScript: `../checks/{r['id'].lower()}.py`\n\n## What I got wrong the first time\n")
    gitkeep(d / "checks")


# ---------------------------------------------------------------- phase 2
def phase2():
    ph, d = P["p2"], ROOT / "phase-2-drills"
    rows = table(["#", "Implementation", "Time target", "Must get right", "Drilled in", "Folder"],
                 [[x["row"], x["name"], x["target"], x["must"], x["where"], f"`{x['row']:02d}-{x['slug'].replace('_', '-')}/`"] for x in ph["drills"]])
    readme(d / "README.md", f"""{head(ph)}
{rows}

{paras(ph['after'])}

[Neural Networks: Zero to Hero playlist](https://www.youtube.com/playlist?list={ph['playlist']['list']})

## How to run a drill
1. AI tools and autocomplete off. Start a timer.
2. Write the implementation from a blank file in `NN-name/attempts/YYYY-MM-DD.py`.
3. Run `pytest tests/test_NN.py` (the agent-built harness checks it against the PyTorch reference).
4. Log it in `drill_log.csv` and on the site (Under target / Missed). Three under target in a row clears the row.
{sources(ph['sources'])}""")
    for x in ph["drills"]:
        f = d / f"{x['row']:02d}-{x['slug'].replace('_', '-')}"
        readme(f / "README.md", f"# Drill {x['row']}: {x['name']}\n\n**Time target:** {x['target']}\n\n**Must get right:** {x['must']}\n\n**Drilled in:** {x['where']}\n\nSave each timed attempt as `attempts/YYYY-MM-DD.py`, written from a blank file with AI off.\n")
        gitkeep(f / "attempts")
    keep(d / "tests" / "README.md", "# Drill harness\n\nAGENT-maintained: one `test_NN.py` per drill row that imports your latest attempt and asserts it against the PyTorch reference, plus a timer. You write the implementations; the agent writes and maintains these tests.\n")
    keep(d / "drill_log.csv", "date,row,drill,minutes,target_minutes,under_target,mistake")


# ---------------------------------------------------------------- phase 3
def phase3():
    ph, d = P["p3"], ROOT / "phase-3-papers"
    mods = {m["id"]: m for m in D["modules"]}
    index_rows = []
    for p in D["papers"]:
        m = mods[p["module"]]
        pd = d / f"module-{m['id']}-{m['slug']}" / f"{p['n']:02d}-{p['slug']}"
        rel = pd.relative_to(d).as_posix()
        index_rows.append([p["n"], f"[{p['short']}]({rel}/)", p["year"], f"M{m['id']}"])
        links = [f"- [{l['label']}]({l['url']})" for l in p["paper"]] + [f"- [{l['label']}]({l['url']})" for l in p["resources"]]
        vids = [f"- ▶ [{v['title']}](https://www.youtube.com/watch?v={v['id']})" for v in p["videos"]]
        exps = "\n".join(f"{i}. **{x['tag']}** — {x['body']}\n   - Code: `experiments/exp{i}_{slug(x['body'], 32).replace('-', '_')}.ipynb`"
                         for i, x in enumerate(p["experiments"], 1))
        readme(pd / "README.md", f"""# Paper {p['n']}: {p['short']} ({p['year']})

*{p['title']}* · Module {m['id']} — {m['title']} · [Track on the site]({SITE}#paper-{p['n']})

## Paper and resources
{chr(10).join(links)}

## Walkthrough videos
{chr(10).join(vids)}

## Study approach
{p['approach']}
{f"{chr(10)}## Interview hooks{chr(10)}{p['hooks']}{chr(10)}" if p['hooks'] else ""}
## Break-it experiments
{exps}
{f"{chr(10)}{p['note']}{chr(10)}" if p['note'] else ""}
## Folder guide
| Path | What goes there |
| --- | --- |
| `notes.md` | Day 1 questions, Day 2 derivation, Day 3 results (yours, never overwritten) |
| `experiments/` | Day 3 notebooks or scripts, one per experiment above |
| `figures/` | The plot that shows what broke |
""")
        rows = "\n".join(f"| {x['tag']}: {x['body'][:60]}… | | | |" for x in p["experiments"])
        keep(pd / "notes.md", f"""# Paper {p['n']}: {p['short']} — my notes

## Day 1 — Read and question
Three questions I can't answer yet:
1.
2.
3.

## Day 2 — Derive and watch
Core derivation, by hand:

```
(paste or photograph it; link images from ./figures/)
```

## Day 3 — Break it
| Experiment | What I changed | What happened | Why |
| --- | --- | --- | --- |
{rows}

## Explain it aloud
Ten minutes with an LLM as examiner, no notes. Gaps found:

## Two-line conclusion
""")
        gitkeep(pd / "experiments"); gitkeep(pd / "figures")
    readme(d / "README.md", f"""{head(ph)}
{table(["#", "Paper", "Year", "Module"], index_rows)}

{paras(ph['after'])}
{sources(ph['sources'])}""")


# ---------------------------------------------------------------- phase 4
def phase4():
    ph, d = P["p4"], ROOT / "phase-4-systems"
    rows = []
    for c in ph["clusters"]:
        rows.append([f"[{c['name']}]({c['slug']}/)", c["question"]])
        readme(d / c["slug"] / "README.md", f"# {c['name']}\n\n**Read:** {c['read']}\n\n**Must master:** {c['master']}\n\n**HAND implementation:** {c['hand']}\n\n**Known interview question:** {c['question']}\n")
        keep(d / c["slug"] / "notes.md", f"# {c['name']} — my notes\n\n## Answer to the known question, out loud version\n\n## Notes from the reading\n")
    readme(d / "README.md", f"{head(ph)}\n{table(['Cluster', 'Known interview question'], rows)}\n\n{paras(ph['after'])}\n{sources(ph['sources'])}")


# ---------------------------------------------------------------- phase 5
def phase5():
    ph, d = P["p5"], ROOT / "phase-5-leetcode"
    readme(d / "README.md", f"""{head(ph)}
{table(["Topic", "Reach fluency in", "ML tie-in"], [[t["topic"], t["reach"], t["tie"]] for t in ph["topics"]])}

{paras(ph['after'])}

Log every problem in `log.csv`; keep solutions in `solutions/`.
{sources(ph['sources'])}""")
    keep(d / "log.csv", "date,list,problem,pattern,minutes,mistake")
    gitkeep(d / "solutions")


# ---------------------------------------------------------------- phase 6
def phase6():
    ph, d = P["p6"], ROOT / "phase-6-portfolio"
    pf = "\n".join(f"{i}. {x['text']}" for i, x in enumerate(ph["portfolio"], 1))
    prep = "\n\n".join(f"**{x['title']}.** {x['text']}" for x in ph["prep"])
    readme(d / "README.md", f"""{head(ph)}
{pf}

{ph['afterPortfolio']}

{prep}

## In this folder
| Path | What goes there |
| --- | --- |
| `projects.md` | The three public repos, each with its hypothesis, ablation and plot |
| `narratives/` | One-page "why" narrative per project |
| `rapid-fire.md` | Your spoken-answer notes for the rapid-fire set |
| `job-talk/` | Slides and rehearsal notes |

Behavioral stories are personal; keep them in a private repo or notes app, not here.
{sources(ph['sources'])}""")
    keep(d / "projects.md", "# Portfolio projects\n\n| # | Repo | Hypothesis | One-line change that broke it | Plot | Design-choice list done? |\n| --- | --- | --- | --- | --- | --- |\n| 1 | | | | | |\n| 2 | | | | | |\n| 3 | | | | | |")
    keep(d / "rapid-fire.md", "# Rapid-fire answers\n\n- Ways to encode position:\n- 5D parallelism:\n- PPO vs GRPO:\n- Pre- vs post-norm:\n- LoRA layer choice:\n- Why Flash Attention is faster without changing the math:\n- KV-cache formula:\n- Chinchilla's N* and D*:")
    gitkeep(d / "narratives"); gitkeep(d / "job-talk")


# ---------------------------------------------------------------- phase 7
def phase7():
    ph, d = P["p7"], ROOT / "phase-7-job-search"
    groups = "\n\n".join(f"## {g['title']}\n" + "\n".join(f"{'1.' if g['ordered'] else '-'} {i['text']}" for i in g["items"]) for g in ph["groups"])
    readme(d / "README.md", f"""{head(ph)}
{groups}

{paras(ph['after'])}

## Keep this private
Contacts, applications, offers and negotiation notes should not live in a public repo. `private/` in this folder is git-ignored; use it for local notes only.
{sources(ph['sources'])}""")
    gitkeep(d / "private")


for fn in (phase0, phase1, phase2, phase3, phase4, phase5, phase6, phase7):
    fn()
print(f"Phase folders ready. New personal files: {len(made)}.")
